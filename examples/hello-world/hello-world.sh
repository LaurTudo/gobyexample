# Pentru a rula programul, pune codul în `hello-world.go`
# și folosește `go run`.
$ go run hello-world.go
hello world

# Uneori vom dori să compilăm programele noastre în
# fișiere binare. Putem face asta folosind `go build`.
$ go build hello-world.go
$ ls
hello-world	hello-world.go

# Apoi putem executa direct binarul compilat.
$ ./hello-world
hello world

